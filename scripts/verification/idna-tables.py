#!/usr/bin/env python3
"""Derive IDNA context checks from the repository's pinned Unicode 17 tables."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[2]
data=(root/'internal/goruntime/unicode17/idna_data.go').read_text()
normal=(root/'internal/goruntime/unicode17/normalization_data.go').read_text()
def ranges(rows):
 return ''.join('\\u{'+a+'}'+('' if a==b else '-\\u{'+b+'}') for a,b in rows)
def groups(name):
 text=data.split('var '+name+' =',1)[1].split('\n}',1)[0]
 result={}
 for a,b,label in re.findall(r'\{0x([a-f0-9]+), 0x([a-f0-9]+), "([A-Z]+)"\}',text):result.setdefault(label,[]).append((a,b))
 return result
license=(root/'internal/goruntime/unicode17/LICENSE.txt').read_text()
source='/*\n'+license+'\n*/\n// Generated by scripts/verification/idna-tables.py from pinned Unicode 17 tables.\n'
source+='type CharacterClass = readonly [RegExp, string];\n'
for name,default in [('bidiClasses','L'),('joiningTypes','U')]:
 source+='const '+name+': readonly CharacterClass[] = [\n'
 for label,rows in groups(name).items():
  if label!=default:source+='  [/['+ranges(rows)+']/u, "'+label+'"],\n'
 source+='];\n'
 fn='idnaBidiClass' if name=='bidiClasses' else 'idnaJoiningType'
 source+='export function '+fn+'(value: string): string { return '+name+'.find((entry: CharacterClass): boolean => entry[0].test(value))?.[1] ?? "'+default+'"; }\n'
rows=[(a,b) for a,b in re.findall(r'\{0x([a-f0-9]+), 0x([a-f0-9]+), 9\}',normal.split('var canonicalClasses =',1)[1].split('\n}',1)[0])]
source+='export function idnaVirama(value: string): boolean { return /['+ranges(rows)+']/u.test(value); }\n'
(root/'internal/target/typescript/runtime/schema/assertions/wire-format-idna-context.ts').write_text(source)
