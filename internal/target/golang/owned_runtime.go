package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"path"
	"strconv"
	"strings"

	"openapi-sdkgen/internal/generator"
	"openapi-sdkgen/internal/goruntime"
)

const canonicalRuntimeRoot = "openapi-sdkgen/internal/goruntime/"

// ownedRuntimeFile rewrites only AST import literals. Pattern/string data,
// comments, notices and package identities are preserved verbatim in meaning.
func ownedRuntimeFile(source, root string) ([]byte, []importPlan, error) {
	data, err := goruntime.Sources.ReadFile(source)
	if err != nil {
		return nil, nil, err
	}
	if path.Ext(source) != ".go" {
		return data, nil, nil
	}
	set := token.NewFileSet()
	node, err := parser.ParseFile(set, source, data, parser.ParseComments)
	if err != nil {
		return nil, nil, err
	}
	var imports []importPlan
	for _, spec := range node.Imports {
		value, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return nil, nil, err
		}
		if strings.HasPrefix(value, canonicalRuntimeRoot) {
			value = root + "/internal/runtime/" + strings.TrimPrefix(value, canonicalRuntimeRoot)
			spec.Path.Value = strconv.Quote(value)
		}
		alias := ""
		if spec.Name != nil {
			alias = spec.Name.Name
		}
		imports = append(imports, importPlan{Alias: alias, Path: value})
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by openapi-sdkgen. DO NOT EDIT.\n\n")
	if err := format.Node(&out, set, node); err != nil {
		return nil, nil, err
	}
	return out.Bytes(), imports, nil
}
func ownedRuntimePlans(config generator.GoOptions, module runtimeModule) ([]filePlan, error) {
	files := make([]filePlan, 0, len(module.Sources))
	for _, source := range module.Sources {
		prepared, imports, err := ownedRuntimeFile(source, config.ImportPath)
		if err != nil {
			return nil, fmt.Errorf("owned Go source %s: %w", source, err)
		}
		files = append(files, filePlan{Path: path.Join(path.Dir(module.Path), path.Base(source)), Package: module.Package, Source: source, Prepared: string(prepared), Imports: imports})
	}
	return files, nil
}
