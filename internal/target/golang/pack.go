package golang

import (
	"bytes"
	"container/list"
	"crypto/sha256"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path"
	"sort"
	"strconv"
	"strings"

	"openapi-sdkgen/internal/generator"
)

const packTargetBytes = 128 << 10
const packBufferBytes = 8 << 20
const packBufferGroups = 128
const generatedGoMarker = "// Code generated by openapi-sdkgen. DO NOT EDIT."

type packPart struct {
	artifact generator.Artifact
	body     int
}

type packGroup struct {
	key, directory string
	header         []byte
	parts          []packPart
	bytes, output  int
	element        *list.Element
}

// Packing happens after partition/import binding. Only file-local declarations
// with the exact same imports may share a file; package placement never changes.
type artifactPacker struct {
	sink                  generator.ArtifactSink
	target, limit, bytes  int
	groups                map[string]*packGroup
	order                 list.List
	inputs, outputs       map[[32]byte]struct{}
	unsafeDirectories     map[string]bool
	generatedArtifacts    bool
	err                   error
	peakBytes, peakGroups int
}

func newArtifactPacker(sink generator.ArtifactSink, target, limit int) *artifactPacker {
	return &artifactPacker{sink: sink, target: target, limit: limit, groups: make(map[string]*packGroup), inputs: make(map[[32]byte]struct{}), outputs: make(map[[32]byte]struct{})}
}

func (p *artifactPacker) WriteArtifact(artifact generator.Artifact) error {
	if p.err != nil {
		return p.err
	}
	identity := sha256.Sum256([]byte(artifact.Path))
	if _, exists := p.inputs[identity]; exists {
		p.err = fmt.Errorf("duplicate original Go artifact %s", artifact.Path)
		return p.err
	}
	if _, exists := p.outputs[identity]; exists {
		p.err = fmt.Errorf("packed Go artifact collides with original %s", artifact.Path)
		return p.err
	}
	p.inputs[identity] = struct{}{}
	directory := path.Dir(artifact.Path)
	if p.unsafeDirectories[directory] || strings.HasPrefix(directory, "internal/modelsimpl/") && p.unsafeDirectories["models"] || strings.HasPrefix(directory, "internal/schemaimpl/") && p.unsafeDirectories["internal/schema"] {
		return p.write(artifact, true)
	}
	key, header, body, ok := packableArtifact(artifact, p.target, p.generatedArtifacts)
	if !ok || len(artifact.Data) > p.limit {
		return p.write(artifact, true)
	}
	group := p.groups[key]
	bodyBytes := len(bytes.TrimSpace(artifact.Data[body:])) + 2
	if len(header)+bodyBytes > p.target {
		return p.write(artifact, true)
	}
	if group != nil && group.output+bodyBytes > p.target {
		if err := p.flush(group); err != nil {
			return err
		}
		group = nil
	}
	for p.bytes+len(artifact.Data) > p.limit || group == nil && len(p.groups) >= packBufferGroups {
		oldest := p.order.Front()
		if oldest == nil {
			break
		}
		old := oldest.Value.(*packGroup)
		if old == group {
			group = nil
		}
		if err := p.flush(old); err != nil {
			return err
		}
	}
	if group == nil {
		group = &packGroup{key: key, directory: path.Dir(artifact.Path), header: header, output: len(header)}
		group.element = p.order.PushBack(group)
		p.groups[key] = group
	}
	group.parts = append(group.parts, packPart{artifact: artifact, body: body})
	group.bytes += len(artifact.Data)
	group.output += bodyBytes
	p.bytes += len(artifact.Data)
	p.peakBytes = max(p.peakBytes, p.bytes)
	p.peakGroups = max(p.peakGroups, len(p.groups))
	return nil
}

func (p *artifactPacker) write(artifact generator.Artifact, original bool) error {
	identity := sha256.Sum256([]byte(artifact.Path))
	_, emitted := p.outputs[identity]
	_, input := p.inputs[identity]
	if emitted || input && !original {
		p.err = fmt.Errorf("duplicate final Go artifact %s", artifact.Path)
		return p.err
	}
	p.outputs[identity] = struct{}{}
	p.err = p.sink.WriteArtifact(artifact)
	return p.err
}

func (p *artifactPacker) flush(group *packGroup) error {
	delete(p.groups, group.key)
	p.order.Remove(group.element)
	p.bytes -= group.bytes
	if len(group.parts) == 1 {
		return p.write(group.parts[0].artifact, true)
	}
	var content bytes.Buffer
	content.Grow(group.output)
	content.Write(group.header)
	for _, part := range group.parts {
		content.Write(bytes.TrimSpace(part.artifact.Data[part.body:]))
		content.WriteString("\n\n")
	}
	// The first original path keeps unrelated groups stable across re-emission.
	identity := sha256.Sum256([]byte(group.key + "\x00" + group.parts[0].artifact.Path))
	name := path.Join(group.directory, fmt.Sprintf("packed_%x.go", identity))
	return p.write(generator.Artifact{Path: name, Data: bytes.TrimSuffix(content.Bytes(), []byte("\n"))}, false)
}

func (p *artifactPacker) finish() error {
	if p.err != nil {
		return p.err
	}
	for p.order.Len() != 0 {
		if err := p.flush(p.order.Front().Value.(*packGroup)); err != nil {
			return err
		}
	}
	return nil
}

func packableArtifact(artifact generator.Artifact, target int, generated bool) (string, []byte, int, bool) {
	name := path.Base(artifact.Path)
	if !strings.HasSuffix(name, ".go") || len(artifact.Data) > target || !generated && !bytes.HasPrefix(artifact.Data, []byte(generatedGoMarker+"\n")) {
		return "", nil, 0, false
	}
	for _, component := range strings.Split(artifact.Path, "/") {
		if strings.HasPrefix(component, "_") || strings.HasPrefix(component, ".") {
			return "", nil, 0, false
		}
	}
	stem := strings.TrimSuffix(name, ".go")
	for _, suffix := range strings.Fields("test aix android darwin dragonfly freebsd hurd illumos ios js linux nacl netbsd openbsd plan9 solaris wasip1 windows zos 386 amd64 amd64p32 arm armbe arm64 arm64be loong64 mips mipsle mips64 mipsle64 mips64p32 mips64p32le ppc ppc64 ppc64le riscv riscv64 s390 s390x sparc sparc64 wasm") {
		if strings.HasSuffix(stem, "_"+suffix) || strings.Contains(stem, "_"+suffix+"_") {
			return "", nil, 0, false
		}
	}
	set := token.NewFileSet()
	node, err := parser.ParseFile(set, artifact.Path, artifact.Data, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return "", nil, 0, false
	}
	body := set.Position(node.Name.End()).Offset
	imports := make([]string, 0, len(node.Imports))
	for _, declaration := range node.Decls {
		switch declaration := declaration.(type) {
		case *ast.GenDecl:
			if declaration.Tok == token.VAR {
				return "", nil, 0, false
			}
			if declaration.Tok == token.IMPORT {
				body = set.Position(declaration.End()).Offset
			}
		case *ast.FuncDecl:
			if declaration.Recv == nil && declaration.Name.Name == "init" {
				return "", nil, 0, false
			}
		}
	}
	for _, group := range node.Comments {
		for _, comment := range group.List {
			text := comment.Text
			if strings.HasPrefix(text, "//go:") || strings.HasPrefix(text, "//line ") || strings.HasPrefix(text, "/*line ") || strings.HasPrefix(text, "//export ") || strings.Contains(text, "#cgo") || strings.Contains(text, "+build") || set.Position(comment.Pos()).Offset < body && text != generatedGoMarker {
				return "", nil, 0, false
			}
		}
	}
	for _, imported := range node.Imports {
		alias := ""
		if imported.Name != nil {
			alias = imported.Name.Name
		}
		location, err := strconv.Unquote(imported.Path.Value)
		if err != nil || alias == "." || alias == "_" || location == "C" {
			return "", nil, 0, false
		}
		imports = append(imports, alias+" "+strconv.Quote(location))
	}
	sort.Strings(imports)
	key := path.Dir(artifact.Path) + "\x00" + node.Name.Name + "\x00" + strings.Join(imports, "\n")
	header := generatedGoMarker + "\n\npackage " + node.Name.Name + "\n"
	if len(imports) != 0 {
		header += "\nimport (\n" + strings.Join(imports, "\n") + "\n)\n"
	}
	formatted, err := format.Source([]byte(header))
	if err != nil {
		return "", nil, 0, false
	}
	return key, append(formatted, '\n'), body, true
}
