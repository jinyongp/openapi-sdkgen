package golang

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"path"
	"strconv"
	"strings"
	"text/template"

	"openapi-sdkgen/internal/generator"
)

//go:embed templates/*.go.tmpl runtime/*.go.tmpl
var sources embed.FS

func (Generator) EmitTo(plan generator.Plan, sink generator.ArtifactSink) error {
	if sink == nil {
		return fmt.Errorf("Go artifact sink is required")
	}
	value, err := plan.Value("golang")
	if err != nil {
		return err
	}
	prepared, ok := value.(sourcePlan)
	if !ok {
		return fmt.Errorf("invalid Go source plan")
	}
	originalSink := sink
	schemaBindings := make(map[string]partitionReference)
	modelBindings := make(map[string]partitionReference)
	packages := make(map[string][]partitionFile)
	shared := make(map[string]bool)
	for _, file := range prepared.Files {
		shared[file.Path] = file.Source != "" || strings.HasPrefix(file.Template, "runtime/")
	}
	sink = generator.ArtifactSinkFunc(func(artifact generator.Artifact) error {
		directory := path.Dir(artifact.Path)
		if directory != "internal/schema" {
			var err error
			artifact, err = bindPartitionImports(artifact, prepared.ImportPath+"/internal/schema", schemaBindings)
			if err != nil {
				return err
			}
		}
		if directory != "models" {
			var err error
			artifact, err = bindPartitionImports(artifact, prepared.ImportPath+"/models", modelBindings)
			if err != nil {
				return err
			}
		}
		if directory == "models" || directory == "internal/schema" {
			packages[directory] = append(packages[directory], partitionFile{artifact: artifact, shared: shared[artifact.Path]})
			return nil
		}
		return originalSink.WriteArtifact(artifact)
	})
	// Retain one package's rendered text at a time. Large source plans already
	// occupy substantial memory before the compiler is started.
	for _, phase := range []string{"internal/schema", "models", ""} {
		for _, file := range prepared.Files {
			directory := path.Dir(file.Path)
			if phase == "" {
				if directory == "models" || directory == "internal/schema" {
					continue
				}
			} else if directory != phase {
				continue
			}
			if file.Source != "" {
				if file.Prepared == "" {
					return fmt.Errorf("missing prepared Go source %s", file.Source)
				}
				// The frozen plan owns immutable formatted text. Each sink receives
				// fresh bytes so a caller cannot mutate a later emission.
				if err := sink.WriteArtifact(generator.Artifact{Path: file.Path, Data: []byte(file.Prepared)}); err != nil {
					return err
				}
				continue
			}

			templateSource, err := sources.ReadFile(file.Template)
			if err != nil {
				return fmt.Errorf("Go template %s: %w", file.Template, err)
			}
			renderer, err := template.New(file.Path).Funcs(template.FuncMap{"quote": strconv.Quote}).Parse(string(templateSource))
			if err != nil {
				return err
			}
			var content bytes.Buffer
			content.WriteString("// Code generated by openapi-sdkgen. DO NOT EDIT.\n\npackage " + file.Package + "\n")
			if len(file.Imports) != 0 {
				content.WriteString("\nimport (\n")
				for _, imported := range file.Imports {
					fmt.Fprintf(&content, "%s %s\n", imported.Alias, strconv.Quote(imported.Path))
				}
				content.WriteString(")\n")
			}
			if err := renderer.Execute(&content, file); err != nil {
				return fmt.Errorf("render %s: %w", file.Path, err)
			}
			formatted, err := format.Source(content.Bytes())
			if err != nil {
				return fmt.Errorf("format generated Go file %s: %w", file.Path, err)
			}
			if err := sink.WriteArtifact(generator.Artifact{Path: file.Path, Data: formatted}); err != nil {
				return err
			}
		}
		if phase != "" {
			var bindings map[string]partitionReference
			if phase == "internal/schema" {
				bindings = schemaBindings
			} else if phase == "models" {
				bindings = modelBindings
			}
			if err := emitPartitioned(packages[phase], prepared.ImportPath, phase, originalSink, bindings); err != nil {
				return err
			}
			delete(packages, phase)
		}
	}
	return nil
}
